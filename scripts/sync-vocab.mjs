// Copies the schema profiler's vocabulary into DataGuard, so both tools recognise column names the same way.
//
//   npm run sync-vocab                       (expects ../schema_profiler next to this folder)
//   node scripts/sync-vocab.mjs path/to/default.yaml [path/to/org.yaml]
//
// Writes config/vocab.shared.json (commit it: the GitHub build doesn't have the profiler folder).
// Org files follow the profiler's rules: tokens are added, "-token" removes one.
import fs from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';

const [base = '../schema_profiler/vocab/default.yaml', ...orgs] = process.argv.slice(2);
const concepts = {};
const abbreviations = {};
const sources = [];

for (const file of [base, ...orgs]) {
  if (!fs.existsSync(file)) {
    console.error(`Not found: ${file}`);
    process.exit(1);
  }
  const data = parse(fs.readFileSync(file, 'utf8')) ?? {};
  for (const [concept, byLang] of Object.entries(data.concepts ?? {})) {
    const words = Array.isArray(byLang) ? byLang : Object.values(byLang ?? {}).flat();
    const bucket = new Set(concepts[concept] ?? []);
    for (const w of words) {
      if (typeof w === 'boolean') throw new Error(`${file}: "${concept}" has a bare yes/no/on/off; quote it.`);
      const t = String(w).toLowerCase();
      if (t.startsWith('-')) bucket.delete(t.slice(1));
      else bucket.add(t);
    }
    concepts[concept] = [...bucket].sort();
  }
  Object.assign(abbreviations, data.abbreviations ?? {});
  sources.push(path.relative(process.cwd(), path.resolve(file)).replaceAll('\\', '/'));
}

const out = { _note: 'Generated by scripts/sync-vocab.mjs from the schema profiler. Do not edit by hand.', sources, syncedAt: new Date().toISOString().slice(0, 10), concepts, abbreviations };
fs.writeFileSync('config/vocab.shared.json', JSON.stringify(out, null, 2) + '\n');
console.log(`config/vocab.shared.json: ${Object.keys(concepts).length} concepts from ${sources.join(', ')}`);
